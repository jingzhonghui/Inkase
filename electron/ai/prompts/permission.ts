import type { AiPermissionMode } from '../../../shared/ai/permission'

/**
 * 把当前权限模式写进系统提示。
 *
 * 只读模式下修改类工具已经从工具列表里剔掉了，但模型仍可能凭上一轮的记忆或
 * 训练里的工具名去调用，结果拿到的是一条「工具不存在」。先用一句话把边界
 * 说清楚，比让它在错误信息里试错更省步骤，也更不容易反复请求同一个操作。
 */
export function buildPermissionInstruction(mode: AiPermissionMode): string {
  if (mode === 'readonly') {
    return [
      '',
      '## 权限模式（只读）',
      '',
      '当前会话是只读模式：你只能读取、检索与分析文档，不能修改、新建、移动或删除任何文件。',
      '修改类工具在本模式下不可用。用户要求改动时，直接说明需要把权限切换为「标准」或「完全控制」，不要尝试用其它工具绕过。'
    ].join('\n')
  }
  if (mode === 'auto') {
    return [
      '',
      '## 权限模式（完全控制）',
      '',
      '当前会话是完全控制模式：写入、移动与删除会立即执行，不再逐次请求批准。',
      '因此更要守住前面的规则——只有用户明确要求时才改动文件，每一步都检查工具返回的结果。'
    ].join('\n')
  }
  return [
    '',
    '## 权限模式（标准）',
    '',
    '当前会话是标准模式：任何修改类工具都会先请求用户批准。用户拒绝后不要重复提交相同操作。'
  ].join('\n')
}
